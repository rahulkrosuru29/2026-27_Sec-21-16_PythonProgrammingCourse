# Type Conversion

a = int(input("Enter an integer: "))
print("float :",float(a))#int to float 
print("str :",str(a))#int to string

b = float(input("Enter a float: "))
print("int :",int(b))#float to int
print("str :",str(b))#float to string

c = input("Enter a number as string: ")
print("int :",int(c))#str to int
print("float :",float(c))#str to float
